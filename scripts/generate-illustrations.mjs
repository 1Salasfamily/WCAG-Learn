// Builds app/illustrations.generated.ts and app/lockup.generated.ts from the
// SVG files in public/. Run after changing any drawing:
//   node scripts/generate-illustrations.mjs
//
// The drawings are inlined into the DOM so they can follow the theme
// attribute; an <img> cannot. Each root <svg> loses role and aria-hidden
// (the React wrapper carries the accessible name) and any fixed width or
// height (CSS sizes it), and keeps its viewBox.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const IMAGES = "public/images";
const HEADER = "// Generated by scripts/generate-illustrations.mjs. Do not edit by hand.\n";

function clean(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>\s*/, "")
    .replace(/<svg([^>]*)>/, (m, attrs) => {
      const kept = attrs
        .replace(/\s(role|aria-hidden|width|height)="[^"]*"/g, "")
        .trim();
      return `<svg ${kept} focusable="false">`;
    })
    .replace(/\n+/g, "\n")
    .trim();
}

const files = readdirSync(IMAGES).filter((f) => f.endsWith(".svg")).sort();
const entries = files.map((f) => {
  const id = f.replace(/\.svg$/, "").replace(/-/g, ".");
  return `  ${JSON.stringify(id)}: ${JSON.stringify(clean(readFileSync(join(IMAGES, f), "utf8")))}`;
});
writeFileSync(
  "app/illustrations.generated.ts",
  `${HEADER}export const ILLUSTRATIONS: Record<string, string> = {\n${entries.join(",\n")}\n};\n`
);
const lockup = clean(readFileSync("public/wcag-learn-lockup-dark.svg", "utf8"));
writeFileSync("app/lockup.generated.ts", `${HEADER}export const LOCKUP = ${JSON.stringify(lockup)};\n`);
console.log(`illustrations: ${files.length} drawings -> app/illustrations.generated.ts; lockup -> app/lockup.generated.ts`);
