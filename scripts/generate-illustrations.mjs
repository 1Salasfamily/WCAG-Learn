// Builds app/illustrations.generated.ts and app/lockup.generated.ts from the
// SVG files in public/. Run after changing any drawing:
//   node scripts/generate-illustrations.mjs
//
// The drawings are inlined into the DOM so they can follow the theme
// attribute; an <img> cannot. Each root <svg> loses role and aria-hidden
// (the React wrapper carries the accessible name) and any fixed width or
// height (CSS sizes it), and keeps its viewBox. Internal ids (gradients,
// masks) get a per-drawing prefix: inlined, they share one document with
// every other drawing on the page, including a second copy of the same
// drawing in the enlarged view, and url(#g) resolves to the first #g.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const IMAGES = "public/images";
const HEADER = "// Generated by scripts/generate-illustrations.mjs. Do not edit by hand.\n";

function scopeIds(svg, prefix) {
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    svg = svg
      .replace(new RegExp(`(\\sid=")${esc}"`, "g"), `$1${prefix}${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, "g"), `url(#${prefix}${id})`)
      .replace(new RegExp(`(href=")#${esc}"`, "g"), `$1#${prefix}${id}"`)
      .replace(new RegExp(`(aria-(?:labelledby|describedby)=")${esc}"`, "g"), `$1${prefix}${id}"`);
  }
  return svg;
}

function clean(svg, prefix) {
  return scopeIds(svg, prefix)
    .replace(/<\?xml[^>]*\?>\s*/, "")
    .replace(/<svg([^>]*)>/, (m, attrs) => {
      const kept = attrs
        .replace(/\s(role|aria-hidden|width|height)="[^"]*"/g, "")
        .trim();
      return `<svg ${kept} focusable="false">`;
    })
    .replace(/\n+/g, "\n")
    .trim();
}

const files = readdirSync(IMAGES).filter((f) => f.endsWith(".svg")).sort();
const entries = files.map((f) => {
  const id = f.replace(/\.svg$/, "").replace(/-/g, ".");
  const prefix = `i${id.replace(/\./g, "-")}-`;
  return `  ${JSON.stringify(id)}: ${JSON.stringify(clean(readFileSync(join(IMAGES, f), "utf8"), prefix))}`;
});
writeFileSync(
  "app/illustrations.generated.ts",
  `${HEADER}export const ILLUSTRATIONS: Record<string, string> = {\n${entries.join(",\n")}\n};\n`
);
const lockup = clean(readFileSync("public/wcag-learn-lockup-dark.svg", "utf8"), "lockup-");
writeFileSync("app/lockup.generated.ts", `${HEADER}export const LOCKUP = ${JSON.stringify(lockup)};\n`);
console.log(`illustrations: ${files.length} drawings -> app/illustrations.generated.ts; lockup -> app/lockup.generated.ts`);
